//! Build helpers for the saxl workspace. Run with `cargo xtask <command>`.

use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

const USAGE: &str = "usage: cargo xtask <types|viewer|wasm|playground|docs|ci>";

/// Where ts-rs writes the generated TypeScript types.
const GENERATED: &str = "crates/saxl-renderer/viewer/src/generated";

fn main() -> ExitCode {
    let Some(cmd) = std::env::args().nth(1) else {
        eprintln!("{USAGE}");
        return ExitCode::from(2);
    };
    let result = match cmd.as_str() {
        "types" => types(),
        "viewer" => viewer(),
        "wasm" => wasm(),
        "playground" => playground(),
        "docs" => docs(),
        "ci" => ci(),
        _ => Err(USAGE.to_owned()),
    };
    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("xtask: {e}");
            ExitCode::FAILURE
        }
    }
}

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("..")
}

/// Regenerates the TypeScript types for scenes and diagnostics.
fn types() -> Result<(), String> {
    let dir = root().join(GENERATED);
    if dir.exists() {
        std::fs::remove_dir_all(&dir).map_err(|e| format!("can't clear {GENERATED}: {e}"))?;
    }
    std::fs::create_dir_all(&dir).map_err(|e| format!("can't create {GENERATED}: {e}"))?;
    let dir = dir
        .canonicalize()
        .map_err(|e| format!("can't resolve {GENERATED}: {e}"))?;
    run_with_env(
        "cargo",
        &[
            "test",
            "-p",
            "saxl-core",
            "-p",
            "saxl-renderer",
            "--features",
            "saxl-core/ts,saxl-renderer/ts",
            "export_bindings",
        ],
        &[("TS_RS_EXPORT_DIR", dir.as_os_str())],
    )
}

/// Bundles the viewer into `crates/saxl-renderer/assets/viewer.js`.
fn viewer() -> Result<(), String> {
    run("npm", &["ci"])?;
    run("npm", &["run", "build", "-w", "@saxl/viewer"])
}

/// The `wasm-bindgen-cli` version, which must equal the `wasm-bindgen` crate's.
const WASM_BINDGEN: &str = "0.2.129";

/// Builds `saxl-wasm` and generates its JS bindings in `playground/web/src/wasm`.
fn wasm() -> Result<(), String> {
    let installed = Command::new("wasm-bindgen")
        .arg("--version")
        .output()
        .ok()
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_owned());
    if installed.as_deref() != Some(&format!("wasm-bindgen {WASM_BINDGEN}")) {
        return Err(format!(
            "wasm-bindgen-cli {WASM_BINDGEN} is required (found {}); install it with:\n  \
             cargo install wasm-bindgen-cli --version {WASM_BINDGEN} --locked",
            installed.as_deref().unwrap_or("none")
        ));
    }
    run(
        "cargo",
        &[
            "build",
            "-p",
            "saxl-wasm",
            "--target",
            "wasm32-unknown-unknown",
            "--release",
        ],
    )?;
    let target = std::env::var("CARGO_TARGET_DIR").unwrap_or_else(|_| "target".to_owned());
    let wasm = format!("{target}/wasm32-unknown-unknown/release/saxl_wasm.wasm");
    run(
        "wasm-bindgen",
        &[
            "--target",
            "web",
            "--out-dir",
            "playground/web/src/wasm",
            &wasm,
        ],
    )
}

/// Builds the wasm bindings, then the playground into `playground/web/dist`.
fn playground() -> Result<(), String> {
    wasm()?;
    run("npm", &["ci"])?;
    run("npm", &["run", "build", "-w", "saxl-playground"])
}

/// Writes `docs/rules/` (one page per diagnostic code, plus an index) from the
/// rule markdown, and `docs/images/` (Snip's 2D views as SVG) for the README.
fn docs() -> Result<(), String> {
    let write = |path: &str, text: &str| {
        let path = root().join(path);
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir)
                .map_err(|e| format!("can't create {}: {e}", dir.display()))?;
        }
        std::fs::write(&path, text).map_err(|e| format!("can't write {}: {e}", path.display()))
    };

    // Rule pages and index.
    let mut codes: Vec<(&str, &str, &str, &str)> = saxl_validator::PARSE_CODES
        .iter()
        .map(|(code, summary)| (*code, "error", "parser", *summary))
        .collect();
    for rule in saxl_validator::rules() {
        let severity = match rule.severity() {
            saxl_core::Severity::Error => "error",
            saxl_core::Severity::Warning => "warning",
            saxl_core::Severity::Info => "info",
        };
        codes.push((rule.code(), severity, "validator", rule.summary()));
    }
    let mut index = String::from(
        "<!-- Generated by `cargo xtask docs`. Do not edit. -->\n\n# Diagnostics\n\n\
         Every problem saxl reports has a stable code. Parse (`P`) and validator errors (`E`) block \
         rendering; warnings (`W`) and infos (`I`) don't, and can be silenced with \
         `allow <CODE> \"reason\"`. `saxl explain <CODE>` prints the same pages in the terminal.\n\n\
         | Code | Severity | Stage | Summary |\n|---|---|---|---|\n",
    );
    for (code, severity, stage, summary) in &codes {
        let doc =
            saxl_validator::explain(code).ok_or_else(|| format!("no documentation for {code}"))?;
        let (title, body) = doc.split_once('\n').unwrap_or((doc, ""));
        let source = format!("crates/saxl-validator/rules/{code}.md");
        let page = format!(
            "<!-- Generated by `cargo xtask docs` from {source}. Do not edit. -->\n\n{title}\n\n\
             **Severity:** {severity} · **Stage:** {stage}\n{body}\n[All diagnostics](README.md)\n"
        );
        write(&format!("docs/rules/{code}.md"), &page)?;
        index.push_str(&format!(
            "| [{code}]({code}.md) | {severity} | {stage} | {} |\n",
            summary.replace('|', "\\|")
        ));
    }
    write("docs/rules/README.md", &index)?;

    // README images.
    let snip = std::fs::read_to_string(root().join("examples/snip.saxl"))
        .map_err(|e| format!("can't read Snip: {e}"))?;
    let parsed = saxl_parser::parse(&snip, saxl_core::FileId(0));
    let model = saxl_validator::validate(parsed.model)
        .model
        .ok_or_else(|| "Snip has errors".to_owned())?;
    for view in saxl_renderer::views(&model) {
        if view == saxl_renderer::ViewKind::Tower {
            continue;
        }
        let scene = saxl_renderer::scene(&model, &view).map_err(|e| e.to_string())?;
        let svg = saxl_renderer::to_svg(&scene).map_err(|e| e.to_string())?;
        write(&format!("docs/images/snip-{}.svg", view.slug()), &svg)?;
    }
    eprintln!("wrote docs/rules/ ({} pages) and docs/images/", codes.len());
    Ok(())
}

/// Runs what CI runs: the `rust`, `self-check`, and `generated` jobs.
fn ci() -> Result<(), String> {
    run("cargo", &["fmt", "--all", "--check"])?;
    run(
        "cargo",
        &[
            "clippy",
            "--workspace",
            "--all-targets",
            "--",
            "-D",
            "warnings",
        ],
    )?;
    run("cargo", &["test", "--workspace"])?;
    run(
        "cargo",
        &[
            "run",
            "-p",
            "saxl-cli",
            "--",
            "check",
            "examples/snip.saxl",
            "examples/shopfront.saxl",
            "--deny",
            "warnings",
        ],
    )?;
    run(
        "cargo",
        &[
            "run",
            "-p",
            "saxl-cli",
            "--",
            "fmt",
            "--check",
            "examples/snip.saxl",
            "examples/shopfront.saxl",
        ],
    )?;
    types()?;
    viewer()?;
    docs()?;
    run("npm", &["run", "typecheck", "-w", "@saxl/viewer"])?;
    run(
        "git",
        &[
            "diff",
            "--exit-code",
            "--",
            GENERATED,
            "crates/saxl-renderer/assets/viewer.js",
            "docs/rules",
            "docs/images",
        ],
    )
}

fn run(program: &str, args: &[&str]) -> Result<(), String> {
    run_with_env(program, args, &[])
}

fn run_with_env(
    program: &str,
    args: &[&str],
    env: &[(&str, &std::ffi::OsStr)],
) -> Result<(), String> {
    eprintln!("$ {program} {}", args.join(" "));
    let status = Command::new(program)
        .args(args)
        .envs(env.iter().copied())
        .current_dir(root())
        .status()
        .map_err(|e| format!("failed to run {program}: {e}"))?;
    if status.success() {
        Ok(())
    } else {
        Err(format!("{program} {} failed", args.join(" ")))
    }
}
